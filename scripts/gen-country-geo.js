#!/usr/bin/env node
// Writes client/src/utils/country-geo.js: for each country, where the
// Resolution Map lands an answer that has no city point (the middle of the
// country's addresses, not of its land, so Russia's is near Moscow), and which
// world-atlas outline is that country's, for the glow when it is hit.
//
// Run by hand after `npm run geo:cities`; the output is committed. Both come
// from DB-IP City Lite, so a country DB-IP knows has a point even when the
// atlas is too coarse to draw it (Singapore, Malta).
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const projectDir = path.resolve(__dirname, '..');
const clientModules = path.join(projectDir, 'client/node_modules');
const outFile = path.join(projectDir, 'client/src/utils/country-geo.js');
// world-atlas names that are not the name client/src/utils/countries.js uses.
const ATLAS_NAMES = {
  US: '840',
  CD: '180',
  DO: '214',
  FK: '238',
  GL: '304',
  TF: '260',
  PR: '630',
  CI: '384',
  CF: '140',
  GQ: '226',
  NC: '540',
  SB: '090',
  BA: '070',
  MK: '807',
  SS: '728',
  EH: '732',
};
const load = (spec) => import(pathToFileURL(path.join(clientModules, spec)).href);

async function main() {
  const { decodeCityTable } = await import(
    pathToFileURL(path.join(projectDir, 'server/src/utils/geo-cities.js')).href
  );
  const { feature } = await load('topojson-client/src/index.js');
  const { COUNTRIES } = await import(
    pathToFileURL(path.join(projectDir, 'client/src/utils/countries.js')).href
  );
  const atlas = JSON.parse(
    fs.readFileSync(path.join(clientModules, 'world-atlas/countries-110m.json'), 'utf8'),
  );
  // Outlines are matched by name; the atlas abbreviates a few.
  const byName = new Map(COUNTRIES.map((c) => [c.name.toLowerCase(), c.code]));
  const outlineOf = new Map(Object.entries(ATLAS_NAMES));
  for (const f of feature(atlas, atlas.objects.countries).features) {
    const cc = byName.get(f.properties.name.toLowerCase());
    if (cc && f.id) outlineOf.set(cc, f.id);
  }

  const table = decodeCityTable(
    fs.readFileSync(path.join(projectDir, 'server/assets/geo-cities.bin')),
  );
  const { starts, countries, lats, lons } = table.families[4];
  const rad = Math.PI / 180;
  // Address-weighted mean on the sphere (unit vectors), so a country across
  // the antimeridian (Fiji) does not average to the other side of the world.
  const sums = new Map();
  for (let i = 0; i < starts.length; i++) {
    if (!countries[i]) continue;
    const next = i + 1 < starts.length ? starts[i + 1] : 2 ** 32;
    const weight = next - starts[i];
    const cc = String.fromCharCode(countries[i] >> 8, countries[i] & 0xff);
    const lat = lats[i] / 100;
    const lon = lons[i] / 100;
    const s = sums.get(cc) || { x: 0, y: 0, z: 0 };
    s.x += weight * Math.cos(lat * rad) * Math.cos(lon * rad);
    s.y += weight * Math.cos(lat * rad) * Math.sin(lon * rad);
    s.z += weight * Math.sin(lat * rad);
    sums.set(cc, s);
  }

  const entries = [];
  for (const [cc, s] of [...sums].sort((a, b) => a[0].localeCompare(b[0]))) {
    const lon = Math.atan2(s.y, s.x) / rad;
    const lat = Math.atan2(s.z, Math.hypot(s.x, s.y)) / rad;
    const outline = outlineOf.get(cc) || null;
    entries.push([cc, [Number(lon.toFixed(2)), Number(lat.toFixed(2))], outline]);
  }

  const body = entries
    .map(
      ([cc, at, outline]) =>
        `  ${cc}: { at: [${at.join(', ')}], outline: ${outline ? `'${outline}'` : 'null'} },`,
    )
    .join('\n');
  fs.writeFileSync(
    outFile,
    `// Generated by scripts/gen-country-geo.js from DB-IP City Lite (${table.header.month},\n` +
      `// ${table.header.license}) and world-atlas countries-110m. Do not edit by hand.\n` +
      `//\n// at: where an answer with no city point lands, [lon, lat], the middle of the\n` +
      `// country's addresses. outline: the world-atlas feature id, null when the atlas\n` +
      `// is too coarse to draw the country.\n` +
      `export const COUNTRY_GEO = {\n${body}\n};\n`,
  );
  const missing = entries.filter((e) => !e[2]).map((e) => e[0]);
  console.log(
    `${entries.length} countries written; ${missing.length} without an outline: ${missing.join(' ')}`,
  );
}

main().catch((err) => {
  console.error(`gen-country-geo: ${err.message}`);
  process.exit(1);
});
